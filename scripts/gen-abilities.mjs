// Regenerates mods/pokemon-herd/ability-data.js from PokeAPI: each species' abilities as the games
// give them (pokemon_abilities.csv: two normal slots, a hidden one), and each ability's name and
// in-game description (ability_names.csv, ability_flavor_text.csv, English, the latest games);
// and, for the moves the mod uses, what some abilities go by: contact, punch, bite, pulse, sound
// (move_flag_map.csv), a side effect (an effect chance, for Sheer Force) and recoil (Reckless).
// Run: node scripts/gen-abilities.mjs
import { writeFileSync } from "node:fs";

const BASE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/";
// A CSV reader that keeps quoted fields whole (commas and line breaks in them).
function parse(text) {
  const rows = [];
  let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...rest] = rows;
  return rest.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}
async function csv(name) {
  const r = await fetch(BASE + name);
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  return parse(await r.text());
}
const EN = "9";
const keyOf = Object.fromEntries((await csv("abilities.csv")).map((r) => [r.id, r.identifier]));
const nameOf = Object.fromEntries((await csv("ability_names.csv")).filter((r) => r.local_language_id === EN).map((r) => [r.ability_id, r.name]));
const text = {}, textAt = {};
for (const r of await csv("ability_flavor_text.csv")) {
  if (r.language_id !== EN) continue;
  const v = Number(r.version_group_id);
  if (v >= (textAt[r.ability_id] ?? -1)) { textAt[r.ability_id] = v; text[r.ability_id] = r.flavor_text.replace(/\s+/g, " ").trim(); }
}
// Each species: [first, second, hidden] ability ids (0: none).
const slots = {};
for (const r of await csv("pokemon_abilities.csv")) {
  const dex = Number(r.pokemon_id);
  if (!(dex > 0 && dex <= 1025)) continue;
  const s = (slots[dex] ??= [0, 0, 0]);
  s[Number(r.slot) - 1] = Number(r.ability_id);
}
// Only the abilities some species has, numbered from 1 in the file.
const used = [...new Set(Object.values(slots).flat().filter(Boolean))].sort((a, b) => a - b);
const idx = new Map(used.map((id, i) => [id, i + 1]));
const KEYS = ["", ...used.map((id) => keyOf[id])];
const NAMES = ["", ...used.map((id) => nameOf[id] ?? keyOf[id])];
const TEXTS = ["", ...used.map((id) => text[id] ?? "")];
// The moves' flags, as letters: c contact, p punch, b bite, u pulse, s sound, e a side effect, r recoil.
const { MOVE_LIST } = await import("../mods/pokemon-herd/base-stats.js");
const { MOVES, EXCLUSIVE } = await import("../mods/pokemon-herd/moves.js");
const wanted = new Set([...MOVE_LIST.map((m) => m[1]), ...Object.values(MOVES).flat(), ...Object.keys(EXCLUSIVE)].filter((n) => typeof n === "string"));
const moveName = Object.fromEntries((await csv("move_names.csv")).filter((r) => r.local_language_id === EN).map((r) => [r.move_id, r.name]));
const FLAG = { 1: "c", 8: "p", 16: "b", 17: "u", 9: "s" };
const flags = {};
for (const r of await csv("move_flag_map.csv")) if (FLAG[r.move_flag_id]) flags[r.move_id] = (flags[r.move_id] ?? "") + FLAG[r.move_flag_id];
for (const r of await csv("moves.csv")) if (r.effect_chance) flags[r.id] = (flags[r.id] ?? "") + "e";
for (const r of await csv("move_meta.csv")) if (Number(r.drain) < 0) flags[r.move_id] = (flags[r.move_id] ?? "") + "r";
const MOVE_FLAGS = {};
for (const [id, f] of Object.entries(flags)) if (wanted.has(moveName[id])) MOVE_FLAGS[moveName[id]] = [...new Set(f)].sort().join("");
const missing = [...wanted].filter((n) => !Object.values(moveName).includes(n));
const SPECIES = Array.from({ length: 1026 }, (_, d) => (slots[d] ?? [0, 0, 0]).map((id) => idx.get(id) ?? 0));
writeFileSync(new URL("../mods/pokemon-herd/ability-data.js", import.meta.url), `// Generated by scripts/gen-abilities.mjs from PokeAPI. ABILITY_KEYS / ABILITY_NAMES / ABILITY_TEXTS:
// each ability (index 0: none), its id, its name and its description in the latest games.
// SPECIES_ABILITIES[dex]: [first, second, hidden] (0: none), as the games give them.
export const ABILITY_KEYS = ${JSON.stringify(KEYS)};
export const ABILITY_NAMES = ${JSON.stringify(NAMES)};
export const ABILITY_TEXTS = ${JSON.stringify(TEXTS)};
export const SPECIES_ABILITIES = ${JSON.stringify(SPECIES)};
// MOVE_FLAGS[name]: c contact, p punch, b bite, u pulse, s sound, e a side effect, r recoil.
export const MOVE_FLAGS = ${JSON.stringify(MOVE_FLAGS)};
`);
if (missing.length) console.log(`moves not in PokeAPI by name: ${missing.join(", ")}`);
const show = (d) => SPECIES[d].map((i) => KEYS[i] || "-").join("/");
console.log(`Flamethrower ${MOVE_FLAGS.Flamethrower}, Fire Punch ${MOVE_FLAGS["Fire Punch"]}, Crunch ${MOVE_FLAGS.Crunch}, Brave Bird ${MOVE_FLAGS["Brave Bird"]}, Dark Pulse ${MOVE_FLAGS["Dark Pulse"]}, Bug Buzz ${MOVE_FLAGS["Bug Buzz"]}`);
console.log(`${used.length} abilities; Charizard ${show(6)}, Gengar ${show(94)}, Gyarados ${show(130)}, Shedinja ${show(292)}`);
