// Regenerates mods/pokemon-herd/mega-abilities.js from PokeAPI: each Mega Evolution's ability, as
// the games give it (pokemon.csv's "-mega", "-mega-x", "-mega-y" forms, their pokemon_abilities.csv
// slot 1): by the mod's fighter key ("6mX", "94m"), for those the mod has (base-stats.js FORM_BASE).
// Run: node scripts/gen-mega-abilities.mjs
import { writeFileSync } from "node:fs";

const BASE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/";
const csv = async (name) => {
  const r = await fetch(BASE + name);
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  const [head, ...lines] = (await r.text()).trim().split("\n");
  const cols = head.split(",");
  return lines.map((l) => Object.fromEntries(l.split(",").map((v, i) => [cols[i].trim(), v.trim()]))); // (CRLF: the last field kept its \r)
};
const { FORM_BASE } = await import("../mods/pokemon-herd/base-stats.js");
const abil = Object.fromEntries((await csv("abilities.csv")).map((r) => [r.id, r.identifier]));
const first = {};
for (const r of await csv("pokemon_abilities.csv")) if (r.slot === "1") first[r.pokemon_id] = abil[r.ability_id];
const out = {};
for (const p of await csv("pokemon.csv")) {
  const m = /-mega(?:-([xyz]))?$/.exec(p.identifier);
  if (!m || !first[p.id]) continue;
  const key = `${Number(p.species_id)}m${(m[1] ?? "").toUpperCase()}`;
  if (FORM_BASE[key]) out[key] = first[p.id];
}
writeFileSync(new URL("../mods/pokemon-herd/mega-abilities.js", import.meta.url), `// Generated by scripts/gen-mega-abilities.mjs from PokeAPI: each Mega Evolution's ability (its own,
// as the games give it), by the mod's fighter key ("6mX": Mega Charizard X).
export const MEGA_ABILITIES = ${JSON.stringify(out)};
`);
console.log(`${Object.keys(out).length} Megas:`, ["6mX", "6mY", "94m", "475m", "115m", "448m", "303m"].map((k) => `${k} ${out[k]}`).join(", "));
