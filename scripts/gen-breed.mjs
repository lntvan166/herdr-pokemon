// Regenerates mods/pokemon-herd/breed-data.js from PokeAPI: each species' egg groups (a bit per
// group, pokemon_egg_groups.csv: 13 Ditto, 15 No Eggs) and egg cycles (pokemon_species.csv
// hatch_counter: 5–120, most 20), what the Day Care (breed.js) pairs and hatches by.
// Run: node scripts/gen-breed.mjs
import { writeFileSync } from "node:fs";

const BASE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/";
async function csv(name) {
  const r = await fetch(BASE + name);
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  const [head, ...lines] = (await r.text()).trim().split("\n");
  const cols = head.split(",");
  return lines.map((l) => Object.fromEntries(l.split(",").map((v, i) => [cols[i], v])));
}
const groups = [], cycles = [];
for (const row of await csv("pokemon_egg_groups.csv")) {
  const dex = Number(row.species_id), g = Number(row.egg_group_id);
  if (dex > 0 && dex <= 1025 && g > 0) groups[dex] = (groups[dex] ?? 0) | (1 << g);
}
for (const row of await csv("pokemon_species.csv")) {
  const dex = Number(row.id), c = Number(row.hatch_counter);
  if (dex > 0 && dex <= 1025 && Number.isFinite(c)) cycles[dex] = c;
}
const n = 1026;
const G = Array.from({ length: n }, (_, i) => groups[i] ?? (i ? 1 << 15 : 0));
const C = Array.from({ length: n }, (_, i) => cycles[i] ?? 20);
writeFileSync(new URL("../mods/pokemon-herd/breed-data.js", import.meta.url), `// Generated by scripts/gen-breed.mjs from PokeAPI (index: National Dex number). EGG_GROUPS: a bit
// per egg group (1 Monster, 2 Water 1, 3 Bug, 4 Flying, 5 Field, 6 Fairy, 7 Grass, 8 Human-Like,
// 9 Water 3, 10 Mineral, 11 Amorphous, 12 Water 2, 13 Ditto, 14 Dragon, 15 No Eggs); EGG_CYCLES:
// the games' egg cycles (hatch_counter).
export const EGG_GROUPS = [${G.join(",")}];
export const EGG_CYCLES = [${C.join(",")}];
`);
console.log(`Bulbasaur ${G[1].toString(2)} ${C[1]}, Ditto ${G[132].toString(2)}, Mewtwo ${G[150].toString(2)} ${C[150]}, Pichu ${G[172].toString(2)}, Magikarp ${C[129]}`);
