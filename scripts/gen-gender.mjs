// Regenerates mods/pokemon-herd/gender-data.js: each species' chance of being female (PokeAPI's
// gender rate, in eighths; -1 genderless), and the species SpriteCollab draws differently when
// female (sprite/<dex>/0000/0000/0002, and its shiny 0000/0001/0002). Run: node scripts/gen-gender.mjs
import { writeFileSync } from "node:fs";
import { WALKABLE } from "../mods/pokemon-herd/dex.js";

const rates = {};
for (const id of [1, 2, 3]) { // female, male, genderless: each lists species with their rate
  const g = await (await fetch(`https://pokeapi.co/api/v2/gender/${id}/`)).json();
  for (const d of g.pokemon_species_details) {
    const dex = Number(d.pokemon_species.url.match(/\/(\d+)\/$/)[1]);
    rates[dex] = d.rate;
  }
}
const tracker = await (await fetch("https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/tracker.json")).json();
const female = [], femaleShiny = [];
for (const [key, node] of Object.entries(tracker)) {
  const dex = Number(key);
  const base = node.subgroups?.["0000"]?.subgroups;
  if (base?.["0000"]?.subgroups?.["0002"]?.sprite_complete > 0) female.push(dex);
  if (base?.["0001"]?.subgroups?.["0002"]?.sprite_complete > 0) femaleShiny.push(dex);
}
const walk = new Set(WALKABLE);
// Only what differs from half and half (4 eighths), for the species the mod has.
const odd = Object.fromEntries(Object.entries(rates).filter(([d, r]) => walk.has(Number(d)) && r !== 4).sort((a, b) => a[0] - b[0]));
const out = `// Generated by scripts/gen-gender.mjs from PokeAPI and SpriteCollab: do not edit.
// FEMALE_RATE: eighths of a species that are female (-1: genderless); missing: 4, half and half.
export const FEMALE_RATE = ${JSON.stringify(odd)};
// Species with their own female sprite (and shiny female sprite) in SpriteCollab.
export const FEMALE_SPRITE = ${JSON.stringify(female.filter((d) => walk.has(d)))};
export const FEMALE_SHINY = ${JSON.stringify(femaleShiny.filter((d) => walk.has(d)))};
`;
writeFileSync(new URL("../mods/pokemon-herd/gender-data.js", import.meta.url), out);
console.log(Object.keys(rates).length, "species rated;", Object.keys(odd).length, "not half and half;", female.length, "female sprites");
