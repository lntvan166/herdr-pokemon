// Regenerates mods/pokemon-herd/species.js: every Pokémon with a walking animation in PMDCollab's
// SpriteCollab, its English name (PokeAPI), and whether a shiny sprite exists.
// Run: node scripts/gen-species.mjs
import { writeFileSync } from "node:fs";
import { megasFrom } from "../mods/pokemon-herd/megas.js";

const TRACKER = "https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/tracker.json";
const NAMES = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv";

const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.text();
};

const tracker = JSON.parse(await get(TRACKER));
const names = new Map();
for (const line of (await get(NAMES)).split("\n").slice(1)) {
  const [id, lang, name] = line.split(",");
  if (lang === "9" && name) names.set(Number(id), name);
}

const rows = [];
const regional = []; // [dex, form folder, label, has a shiny (1/0)]: Alola, Galar, Hisui, Paldea forms that walk
for (const [key, entry] of Object.entries(tracker)) {
  const dex = Number(key);
  if (!(dex >= 1) || !("Walk" in (entry.sprite_files ?? {}))) continue; // key presence = the file exists
  const shiny = "Walk" in (entry.subgroups?.["0000"]?.subgroups?.["0001"]?.sprite_files ?? {});
  const name = names.get(dex) ?? String(entry.name).replace(/_/g, " ").trim();
  rows.push([dex, name, shiny ? 1 : 0]);
  for (const [form, sub] of Object.entries(entry.subgroups ?? {})) {
    const walks = "Walk" in (sub.sprite_files ?? {});
    const shinyForm = "Walk" in (sub.subgroups?.["0001"]?.sprite_files ?? {}) ? 1 : 0;
    if (walks && /^(Alola|Galar|Hisui|Paldea)(_(Combat|Blaze|Aqua))?$/.test(sub.name)) regional.push([dex, form, sub.name.replace(/_/g, " "), shinyForm]);
  }
}
rows.sort((a, b) => a[0] - b[0]);
const megas = megasFrom(tracker); // dex -> [form folder, has a shiny (1/0)]

const body = rows.map((r) => JSON.stringify(r)).join(",\n  ");
const out = `// GENERATED by scripts/gen-species.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// Every Pokémon with a walking animation in PMDCollab SpriteCollab (tracker.json), with its English
// name from PokeAPI (pokemon_species_names.csv). [dex, name, has a shiny sprite (1/0)].
// Pokémon names are trademarks of Nintendo, Creatures and GAME FREAK; see README.
export const SPECIES = [
  ${body},
];

// Mega forms that walk: dex -> [form folder under sprite/<dex>/, has a shiny (1/0)].
export const MEGA = ${JSON.stringify(megas)};

// Regional forms that walk: [dex, form folder under sprite/<dex>/, label, has a shiny (1/0)].
export const REGIONAL = [
  ${regional.map((r) => JSON.stringify(r)).join(",\n  ")},
];
`;
writeFileSync(new URL("../mods/pokemon-herd/species.js", import.meta.url), out);
console.log(`${rows.length} species, ${rows.filter((r) => r[2]).length} with shiny, ${Object.keys(megas).length} with a Mega, ${regional.length} regional forms`);
