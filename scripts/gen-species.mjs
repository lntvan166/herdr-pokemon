// Regenerates mods/pokemon-herd/species.js: every Pokémon with a walking animation in PMDCollab's
// SpriteCollab, its English name (PokeAPI), and whether a shiny sprite exists.
// Run: node scripts/gen-species.mjs
import { writeFileSync } from "node:fs";
import { megasFrom } from "../mods/pokemon-herd/megas.js";

const TRACKER = "https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/tracker.json";
const NAMES = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv";
const EVOLUTION_CSV = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_evolution.csv";
const ITEMS_CSV = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/items.csv";
const SPECIES_CSV = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv";

const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.text();
};

const tracker = JSON.parse(await get(TRACKER));
const names = new Map();
for (const line of (await get(NAMES)).split("\n").slice(1)) {
  const [id, lang, name] = line.split(",");
  if (lang === "9" && name) names.set(Number(id), name);
}

const rows = [];
const regional = []; // [dex, form folder, label, has a shiny (1/0)]: Alola, Galar, Hisui, Paldea forms that walk
for (const [key, entry] of Object.entries(tracker)) {
  const dex = Number(key);
  if (!(dex >= 1) || !("Walk" in (entry.sprite_files ?? {}))) continue; // key presence = the file exists
  const shiny = "Walk" in (entry.subgroups?.["0000"]?.subgroups?.["0001"]?.sprite_files ?? {});
  const name = names.get(dex) ?? String(entry.name).replace(/_/g, " ").trim();
  rows.push([dex, name, shiny ? 1 : 0]);
  for (const [form, sub] of Object.entries(entry.subgroups ?? {})) {
    const walks = "Walk" in (sub.sprite_files ?? {});
    const shinyForm = "Walk" in (sub.subgroups?.["0001"]?.sprite_files ?? {}) ? 1 : 0;
    if (walks && /^(Alola|Galar|Hisui|Paldea)(_(Combat|Blaze|Aqua))?$/.test(sub.name)) regional.push([dex, form, sub.name.replace(/_/g, " "), shinyForm]);
  }
}
rows.sort((a, b) => a[0] - b[0]);
// Deerling and Sawsbuck's coats: dex -> [[form folder, has a shiny (1/0)] for summer, autumn, winter].
const seasonal = {};
for (const [key, entry] of Object.entries(tracker)) {
  const subs = Object.entries(entry.subgroups ?? {});
  const coats = ["Summer", "Autumn", "Winter"].map((name) => subs.find(([, sub]) => sub.name === name && "Walk" in (sub.sprite_files ?? {})));
  if (coats.every(Boolean)) seasonal[Number(key)] = coats.map(([form, sub]) => [form, "Walk" in (sub.subgroups?.["0001"]?.sprite_files ?? {}) ? 1 : 0]);
}
const megas = megasFrom(tracker);
// What each species evolves from (PokeAPI's evolves_from_species_id), when both walk.
const walks = new Set(rows.map((r) => r[0]));
const evolves = {};
for (const line of (await get(SPECIES_CSV)).split("\n").slice(1)) {
  const [id, , , from] = line.split(",");
  if (from && walks.has(Number(id)) && walks.has(Number(from))) evolves[id] = Number(from);
}
// How each evolves, when it isn't just by levelling up (which here means finishing jobs): a stone,
// friendship, a time of day, or friendship by day or night. Any of a species' ways will do.
// Trades and the odder ways (moves, places, special items) count as levelling up.
const STONES = ["fire", "water", "thunder", "leaf", "moon", "sun", "shiny", "dusk", "dawn", "ice"];
const itemName = new Map((await get(ITEMS_CSV)).split("\n").slice(1).map((l) => l.split(",")).map(([id, name]) => [id, name]));
const [head, ...lines] = (await get(EVOLUTION_CSV)).split("\n");
const col = Object.fromEntries(head.split(",").map((c, i) => [c, i]));
const how = {};
for (const line of lines) {
  const r = line.split(",");
  const dex = r[col.evolved_species_id];
  if (!evolves[dex]) continue;
  const time = r[col.time_of_day] === "day" || r[col.time_of_day] === "night" ? r[col.time_of_day] : "";
  const stone = r[col.evolution_trigger_id] === "3" && /^(\w+)-stone$/.exec(itemName.get(r[col.trigger_item_id]) ?? "")?.[1];
  let way = "jobs";
  if (stone && STONES.includes(stone)) way = `stone:${stone}`;
  else if (r[col.evolution_trigger_id] === "1" && r[col.minimum_happiness]) way = time ? `friend:${time}` : "friend";
  else if (r[col.evolution_trigger_id] === "1" && time) way = time;
  (how[dex] ??= new Set()).add(way);
}
const evolveHow = {};
for (const [dex, ways] of Object.entries(how)) if (!(ways.size === 1 && ways.has("jobs"))) evolveHow[dex] = [...ways].sort(); // dex -> [form folder, has a shiny (1/0)]

const body = rows.map((r) => JSON.stringify(r)).join(",\n  ");
const out = `// GENERATED by scripts/gen-species.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// Every Pokémon with a walking animation in PMDCollab SpriteCollab (tracker.json), with its English
// name from PokeAPI (pokemon_species_names.csv). [dex, name, has a shiny sprite (1/0)].
// Pokémon names are trademarks of Nintendo, Creatures and GAME FREAK; see README.
export const SPECIES = [
  ${body},
];

// Mega forms that walk: dex -> [[form folder under sprite/<dex>/, has a shiny (1/0), "X" | "Y" | ""], ...].
export const MEGA = ${JSON.stringify(megas)};

// Evolutions where both walk: dex -> the dex it evolves from.
export const EVOLVES_FROM = ${JSON.stringify(evolves)};

// Evolutions that need more than jobs: dex -> its ways ("jobs", "stone:<kind>", "friend",
// "friend:day", "friend:night", "day", "night"); any one will do. Missing: jobs only.
export const EVOLVE_HOW = ${JSON.stringify(evolveHow)};

// Coats by season (Deerling, Sawsbuck): dex -> [[form folder, has a shiny (1/0)] for summer, autumn, winter].
export const SEASONAL = ${JSON.stringify(seasonal)};

// Regional forms that walk: [dex, form folder under sprite/<dex>/, label, has a shiny (1/0)].
export const REGIONAL = [
  ${regional.map((r) => JSON.stringify(r)).join(",\n  ")},
];
`;
writeFileSync(new URL("../mods/pokemon-herd/species.js", import.meta.url), out);
console.log(`${rows.length} species, ${rows.filter((r) => r[2]).length} with shiny, ${Object.keys(megas).length} with a Mega, ${regional.length} regional forms, ${Object.keys(evolves).length} evolutions (${Object.keys(evolveHow).length} special), ${Object.keys(seasonal).length} with seasonal coats`);
