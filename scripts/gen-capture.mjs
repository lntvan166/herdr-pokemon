// Regenerates mods/pokemon-herd/capture.js: each species' capture rate in the games (0–255, from
// PokeAPI's pokemon_species.csv), what trainer.js baseRate scales its catch by (common ones a
// little easier, rare ones a little harder). Run: node scripts/gen-capture.mjs
import { writeFileSync } from "node:fs";

const CSV = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv";
const r = await fetch(CSV);
if (!r.ok) throw new Error(`${CSV}: HTTP ${r.status}`);
const [head, ...lines] = (await r.text()).trim().split("\n");
const cols = head.split(",");
const id = cols.indexOf("id"), rate = cols.indexOf("capture_rate");
const out = [];
for (const l of lines) {
  const c = l.split(",");
  const dex = Number(c[id]), v = Number(c[rate]);
  if (dex > 0 && Number.isFinite(v)) out[dex] = v;
}
const list = Array.from({ length: out.length }, (_, i) => out[i] ?? 45);
list[0] = 0;
writeFileSync(new URL("../mods/pokemon-herd/capture.js", import.meta.url), `// Generated by scripts/gen-capture.mjs from PokeAPI's pokemon_species.csv: each species' capture
// rate in the games (0–255; index: its National Dex number). trainer.js baseRate scales by it.
export const CAPTURE = [${list.join(",")}];
`);
console.log(`${list.length - 1} species; Pidgey ${list[16]}, Bulbasaur ${list[1]}, Snorlax ${list[143]}, Beldum ${list[374]}`);
